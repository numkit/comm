const keel::c64 *constellationFor(keel::i32 M, keel::usize &len_out)
{
    switch (M) {
        case 16:
            len_out = 16;
            return kMil16;
        case 32:
            len_out = 32;
            return kMil32;
        case 64:
            len_out = 64;
            return kMil64;
        case 256:
            len_out = 256;
            return kMil256;
        default:
            // Internal invariant: the public entries validate the M
            // set in their <fn>_argcheck first, so this is unreachable
            // through them (kept as defense in depth for other callers).
            throw Error("mil188qam: M must be one of {16, 32, 64, 256}",
                        0, 0, "mil188qam", "",
                        "numkit:mil188qam:UnsupportedM");
    }
}

// <fn>_argcheck for the MIL-STD QAM pair: the M-set contract lives
// here so the interpreter and direct C++ calls answer with ONE
// identifier per function (bugs/opened/lang/reg-domain-logic.md).
void mil188MSetArgcheck(keel::i32 M, keel::StringRef fn)
{
    argcheck::expectedOneOf(keel::as<keel::f64>(M), {16, 32, 64, 256},
                            2, "M", fn);
}

